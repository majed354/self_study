FORMAT_LABEL = {"docx": "Word", "pdf": "PDF"}


def attach_template_files(t):
    files = []
    scope = t.get("scope")
    targets = [("common", "مشترك")] if scope == "common" else [("ug", "البكالوريوس"), ("pg", "الدراسات العليا")]
    for folder, label in targets:
        for fmt in ("docx", "pdf"):
            rel = "files/templates/%s/%s.%s" % (folder, t["slug"], fmt)
            if os.path.exists(rel):
                files.append({"level": folder, "level_name": label, "format": fmt,
                              "format_name": FORMAT_LABEL[fmt], "path": rel,
                              "size": os.path.getsize(rel)})
    return files


def match(inv, kws):
    hits = []
    for s in inv["standards"]:
        for c in s["criteria"]:
            blob = norm(c["text"] + " " + " ".join(e.get("description", "") + " " + e.get("notes", "") for e in c.get("evidence", [])))
            if any(norm(k) in blob for k in kws):
                hits.append(c["id"])
    return hits


